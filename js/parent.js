/* ============================================================
   Кодоквест — задания, которые взрослый задаёт ребёнку.
   Только данные: сам механизм лежит в app.js.

   Главное ограничение, из которого выросла вся эта конструкция: взрослый
   НЕ УМЕЕТ ПРОГРАММИРОВАТЬ. Значит он не может написать ни задачу, ни
   правильный ответ к ней. Но и «пусть напишет условие словами» не годится:
   у задачи без эталона нет проверки, а судья-движок — единственное, чего нет
   у конкурентов. Пустить сюда свободный текст значит убрать движок из
   продукта ровно там, где взрослый на него смотрит.

   Выход: программу пишет ШАБЛОН, а взрослый даёт ЧИСЛА из своей жизни.
   Дальше всё как в разделе «Своё задание»: движок прогоняет программу и сам
   вычисляет ожидаемый вывод, задание уезжает ребёнку ссылкой, сервера не надо.

   Правила для шаблона (их проверяет taskProblem в app.js, а заодно тест
   tests/parent-tasks.js):
     — никакой случайности и никакого input(): у ребёнка выпало бы другое;
     — программа обязана что-то печатать, иначе сверять нечего;
     — только то, что объяснено в курсе: переменные, арифметика, while, for,
       списки, round. Задание не должно требовать незнакомой команды.
   ============================================================ */
