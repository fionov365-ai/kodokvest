/* ---- живые числа в коде витрины ----
   Идея фаундера 07.09.2026: «может добавить интерактив, чтобы люди в коде
   могли менять цифры и программа печатала другое». Именно ЦИФРЫ, а не весь
   код: проект — это шестьдесят-девяносто строк, править их целиком на вывеске
   родитель не станет, а ткнуть в число и увидеть другой результат — станет.
   Заодно сломать программу так нельзя: синтаксис остаётся прежним.

   ⚠️ Числа ищем ТЕМ ЖЕ выражением, что и подсветка, и по сырому коду, а не по
   экранированному: иначе цифра внутри строки («уровень 3») стала бы полем
   ввода, хотя в коде это текст, а не число. Группа 3 в HLRE — как раз число,
   и строки с комментариями разобраны раньше неё. */
function landNums(code){
  var re = new RegExp(A.HLRE.source, "g"), m, out = [];
  while ((m = re.exec(code))){
    if (m[3] !== undefined && m[3] !== "")
      out.push({ start: m.index, end: m.index + m[0].length, val: m[0] });
  }
  return out;
}
function landLiveCode(code, nums){
  var html = "", last = 0;
  nums.forEach(function(n, i){
    html += A.hl(code.slice(last, n.start));
    var len = Math.max(3, n.val.length);
    html += '<input class="numin" type="text" inputmode="numeric" data-n="' + i +
      '" value="' + A.esc(n.val) + '" size="' + n.val.length + '" maxlength="' + len +
      '" aria-label="число в программе, можно поменять">';
    last = n.end;
  });
  return html + A.hl(code.slice(last));
}

